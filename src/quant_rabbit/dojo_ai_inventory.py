"""Fail-closed writer primitives for a future DOJO AI inventory room.

This module does not consume a decision and cannot mutate either a virtual or
real broker.  It only seals one point-in-time, AI-authored, paper-virtual
inventory action and appends it to a strict hash-chained JSONL ledger.  The
separately reviewed virtual-broker consumer may consume a row only after
:func:`validate_virtual_action_binding` proves that the exact decision was
durably recorded before the proposed virtual action.

The contract is intentionally narrow:

* decisions are paper-only and keep ``order_authority=NONE``;
* virtual-broker mutation is explicit while every external broker mutation is
  forbidden;
* the AI request, response, producer, model, and immutable evidence packet are
  content-addressed and fresh at the cutoff;
* every dynamic input is at or before one immutable cutoff;
* the record clock is generated by the writer, never supplied in the proposal;
* a repeated evidence identity is idempotent, while a contradictory decision
  for that identity fails closed;
* a new decision is rejected while the deterministic FX weekly market is
  closed; and
* malformed, truncated, reordered, duplicated, or edited ledger rows prevent
  every later append.

``BLOCK_NEW`` blocks only a new virtual entry.  It does not cancel resting
virtual orders; pending-order cancellation needs a separate future contract.
``ALLOW_NEW_VIRTUAL`` creates only a short-lived, single-use permit receipt
for a later entry proxy.  This writer never submits the entry itself.

There is deliberately no import of the virtual broker, live gateway, OANDA
client, paper-room runner, or active/fixed room code.
"""

