"""「多戦略で少しずつ確実に取れば3倍」を数字にする。

直感は正しい方向だが、証拠金は共有なので本数は素直には効かない。

  N本を同時に建てるなら、1本あたりの想定元本は 1/N になる。
  日次リターン = Σ(各戦略の pips × その戦略の元本) / NAV
              = (pips の平均) × (総元本) / NAV   ← 本数は消える

本数が効くのは次の2経路だけ:
  (1) 回転  保有が短ければ同じ証拠金を1日に何度も使い回せる
  (2) 分散  独立なら日次のブレが減り、ゲートの下限が上がって「確実に」が成立する
分散はリターンの平均を上げない（E[和]=和[E]）。上げるのは回転と1本あたりの優位だけ。

なので必要条件は本数ではなく:

    1取引あたりの純益(pips) × 1日の回転数 × (全証拠金での1pip価値) >= 目標日次JPY

この式に対して、月2倍/3倍/4倍に必要な線を引き、
実測済みの候補がその線のどこに立っているかを重ねて出す。
"""
NAV = 200000
LEV = 25
USDJPY = 157.0
MAX_UNITS = NAV * LEV / USDJPY
PIP_JPY_FULL = MAX_UNITS * 0.01          # 全証拠金を1玉に使ったときの 1pip

print(f"NAV {NAV:,} JPY / レバ {LEV}x → 最大 {MAX_UNITS:,.0f} units / 全力時 1pip = {PIP_JPY_FULL:.0f} JPY\n")

print("=== 本数は素直には効かない ===")
print("同時にN本建てると 1本あたりの元本は 1/N。日次リターンは pips の *平均* で決まり、")
print("本数は式から消える。効くのは (1) 回転 (2) 分散による下限の底上げ、の2つだけ。")
print("分散は平均を上げない。**「少しずつ」を積み上げるのは本数ではなく回転。**\n")

print("=== 月次目標に必要な『1取引あたり純益 pips』 ===")
print(f"{'月倍率':>6s} {'日次%':>7s} {'必要日次JPY':>11s} {'必要日次pips':>12s} | "
      f"{'1回転':>7s} {'3回転':>7s} {'6回転':>7s} {'12回転':>7s}")
print("-" * 88)
for mult in (1.5, 2.0, 3.0, 4.0):
    r = mult ** (1 / 21) - 1
    jpy = NAV * r
    pips = jpy / PIP_JPY_FULL
    row = "".join(f"{pips/t:7.2f}" for t in (1, 3, 6, 12))
    print(f"{mult:6.1f} {100*r:6.2f}% {jpy:11,.0f} {pips:12.1f} | {row}")

print("\n（回転 = 1日に全証拠金を使い切る回数。保有8時間なら3回転、2時間なら12回転が上限）")

print("\n=== 実測済みの候補はどこに立っているか ===")
print("cost_decomposition_long.py の NET/取引（コーパスの水増しコストのまま）と、")
print("その候補の実際の取引頻度から日次を出す。4ペア × 6年 = 約1500営業日。\n")
CAND = [
    # name, hold(min), net pips/trade, trades over 4 pairs x 6y
    ("mom_break@2880",            2880, 3.278, 3195),
    ("vol_squeeze_break@2880",    2880, 1.527, 2369),
    ("vol_squeeze_break@1440",    1440, 0.471, 3741),
    ("mtf_aligned_pullback@2880", 2880, 0.443, 3241),
    ("vol_expansion@960",          960, 0.293, 5657),
    ("fade_stretch@1440",         1440, 0.159, 6469),
    ("fade_range@2880",           2880, 0.118, 3242),
]
DAYS = 1500
print(f"{'候補':26s} {'net/取引':>9s} {'取引/日':>8s} {'日次pips':>9s} {'全力時 日次%':>12s} "
      f"{'月倍率':>8s}")
print("-" * 82)
for name, hold, net, n in CAND:
    tpd = n / DAYS
    dpips = net * tpd
    # 保有が長いほど同時に持つ玉が多く、1玉あたりの元本は 1/(同時建玉数) になる
    concurrent = max(1.0, hold / (24 * 60) * tpd) or 1.0
    dret = dpips * PIP_JPY_FULL / NAV
    print(f"{name:26s} {net:9.3f} {tpd:8.2f} {dpips:9.2f} {100*dret:11.2f}% "
          f"{(1+dret)**21:8.2f}x")

print("=== 回転を上げると、コストが線形に増える（ここが律速）===")
print("実効スプレッド0.80 pips/往復。回転を上げるほど摩擦だけが確実に積み上がる。\n")
print(f"{'回転/日':>7s} {'摩擦 pips/日':>12s} {'摩擦 %/日':>10s} {'3倍に必要な素の pips/取引':>26s}")
print("-" * 60)
need3 = (NAV * (3 ** (1/21) - 1)) / PIP_JPY_FULL
for t in (1, 3, 6, 12, 24):
    fric = t * 0.80
    print(f"{t:7d} {fric:12.1f} {100*fric*PIP_JPY_FULL/NAV:9.2f}% "
          f"{(need3 + fric)/t:26.2f}")
print("""
回転12回/日なら、**何もしなくても 9.6 pips/日 = 1.5%/日 が摩擦で消える**。
3倍に必要な純益 33.7 pips/日 と合わせ、素の優位は 43.3 pips/日 = 1取引あたり 3.61 pips 必要。
受動指値で入口の半スプレッドが消えれば、摩擦は半分の 4.8 pips/日 になる。
**高回転にするほどスプレッドが律速になる。だから受動指値の実証が3倍への必須経路。**
""")

print("""
読み方:
  * これらは **TRAIN/TEST のゲートを通っていない**（portfolio_long.py で
    TRAIN +1.76 → TEST -2.18、下限 -5.53 で不合格）。上の月倍率は
    「もし本物なら」という上限であって、期待値ではない。
  * 全力時の数字なので、同時に複数本を建てればその分だけ割れる。
  * 保有2880分(48h)の候補は同時に2日ぶんの玉を抱えるので、実際には
    全証拠金を1本に使えない。上表はその制約を **考慮していない**（楽観側）。

結論:
  「少しずつ確実に」は算数として成立する。ただし積み上がるのは **本数ではなく回転**で、
  必要なのは **1取引あたり数pipsの純益を、1日に何回も、確実に**。
  実測で最良の候補ですら、楽観的に見て月1.5〜2倍の水準にとどまり、
  しかもその候補は out-of-sample を通っていない。
  **3倍は、回転を上げるか、1取引あたりを上げるか、どちらかの実証が先。**
""")
